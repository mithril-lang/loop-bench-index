"""Typed action library (rung 2 of the derived model, H3).

Every `pure` operation's command is generated by harness code from typed
parameters: paths, source-vocabulary terms, integers. No model writes any part
of it, so a policy (Jev or a deterministic rule) can choose it without an LLM
call. `authored` operations are typed, but one argument is model-written text
(a SPARQL string, a probe script, a derivation). `llm` operations write
artifacts. The library is generic for RDF-bundle/SPARQL artifact tasks; it
names no task-specific class, property or answer.

Operation ids are the proposed Mithril action-ontology individuals
(`https://mithril.fund/id/action/typed/<id>`); they are not yet in
`terminal-actions-v2.mith`.
"""

import json
import shlex

RDF_PARSE = r'''
from pathlib import Path
from rdflib import Graph
def load(paths):
    g = Graph()
    for p in paths:
        p = Path(p)
        for fmt in ('turtle', 'xml', 'nt'):
            try:
                g.parse(p, format=fmt); break
            except Exception:
                continue
        else:
            raise SystemExit(f'UNPARSEABLE {p}')
    return g
def sources(bundle, output_name):
    b = Path(bundle)
    return sorted(b.glob('*.owl')) + sorted(p for p in b.glob('*.ttl') if p.name != output_name)
'''


def py(body, *args):
    script = RDF_PARSE + body
    return 'python3 - ' + ' '.join(shlex.quote(str(a)) for a in args) + " <<'PY'\n" + script + '\nPY'


def list_files(root, depth=2):
    return f'find {shlex.quote(root)} -maxdepth {int(depth)} -type f -print | sort'


def show_file(path, start=1, end=200):
    return f"sed -n '{int(start)},{int(end)}p' {shlex.quote(path)}"


def grep_terms(paths, terms):
    if not terms:
        raise ValueError('grep_terms needs at least one vocabulary term')
    pattern = '|'.join(t.replace('.', r'\.') for t in terms)
    return 'grep -nE ' + shlex.quote(pattern) + ' ' + ' '.join(shlex.quote(p) for p in paths)


def schema_summary(bundle, output_name='unified.ttl'):
    return py(r'''
import sys
from rdflib import RDF, RDFS, OWL
g = load(sorted(Path(sys.argv[1]).glob('*.owl')))
for kind in (OWL.Class, OWL.ObjectProperty, OWL.DatatypeProperty):
    for s in sorted(set(g.subjects(RDF.type, kind))):
        extra = [f'{p.n3(g.namespace_manager)}={o.n3(g.namespace_manager)}' for p in (RDFS.subClassOf, RDFS.subPropertyOf, RDFS.domain, RDFS.range) for o in g.objects(s, p)]
        print(kind.n3(g.namespace_manager), s.n3(g.namespace_manager), ' '.join(extra), sep='\t')
''', bundle)


def term_usage(bundle, output_name='unified.ttl'):
    return py(r'''
import sys
from collections import Counter
from rdflib import RDF
g = load(sources(sys.argv[1], sys.argv[2]))
preds = Counter(g.namespace_manager.normalizeUri(p) for p in g.predicates())
types = Counter(g.namespace_manager.normalizeUri(o) for o in g.objects(None, RDF.type))
for name, count in sorted(preds.items()): print('predicate', name, count, sep='\t')
for name, count in sorted(types.items()): print('class', name, count, sep='\t')
''', bundle, output_name)


def describe_class(bundle, class_term, limit=5, output_name='unified.ttl'):
    return py(r'''
import sys
from rdflib import RDF
g = load(sources(sys.argv[1], sys.argv[4]))
cls = g.namespace_manager.expand_curie(sys.argv[2]) if ':' in sys.argv[2] and not sys.argv[2].startswith('http') else sys.argv[2]
from rdflib import URIRef
for s in sorted(set(g.subjects(RDF.type, URIRef(cls))))[:int(sys.argv[3])]:
    print('#', s.n3(g.namespace_manager))
    for p, o in sorted(g.predicate_objects(s)):
        print('', p.n3(g.namespace_manager), o.n3(g.namespace_manager), sep='\t')
''', bundle, class_term, int(limit), output_name)


def run_entrypoint(script, bundle):
    return f'python3 {shlex.quote(script)} {shlex.quote(bundle)}'


def run_queries(graph, query_files):
    return py(r'''
import sys
g = load([sys.argv[1]])
for q in sys.argv[2:]:
    rows = list(g.query(Path(q).read_text()))
    print('QUERY', q, 'ROWS', len(rows), sep='\t')
    for row in rows:
        print('\t'.join('' if v is None else str(v) for v in row))
''', graph, *query_files)


def preservation_check(bundle, output_name='unified.ttl'):
    return py(r'''
import sys
from rdflib.compare import to_isomorphic, graph_diff
src = load(sources(sys.argv[1], sys.argv[2]))
out = load([Path(sys.argv[1]) / sys.argv[2]])
both, only_src, only_out = graph_diff(to_isomorphic(src), to_isomorphic(out))
print('SOURCE_TRIPLES', len(src), 'OUTPUT_TRIPLES', len(out), 'MISSING_FROM_OUTPUT', len(only_src), 'ADDED', len(only_out), sep='\t')
for t in list(only_src)[:20]: print('MISSING', *[x.n3() for x in t], sep='\t')
raise SystemExit(0 if len(only_src) == 0 else 1)
''', bundle, output_name)


def vocabulary_check(bundle, output_name='unified.ttl'):
    return py(r'''
import sys
from rdflib import RDF
src = load(sources(sys.argv[1], sys.argv[2]))
out = load([Path(sys.argv[1]) / sys.argv[2]])
known = set(src.predicates()) | set(src.objects(None, RDF.type)) | set(src.subjects())
added = set(out) - set(src)
bad = sorted({t for s, p, o in added for t in ([p] + ([o] if p == RDF.type else [])) if t not in known})
print('ADDED_TRIPLES', len(added), 'UNKNOWN_TERMS', len(bad), sep='\t')
for t in bad[:20]: print('UNKNOWN', t.n3(), sep='\t')
raise SystemExit(0 if not bad else 1)
''', bundle, output_name)


def acceptance_check(entrypoint, bundles, query_files, output_name='unified.ttl'):
    """Run the entrypoint on each bundle, then preservation, vocabulary and queries."""
    steps = []
    for bundle in bundles:
        out = f'{bundle.rstrip("/")}/{output_name}'
        steps += [f'echo "== bundle {bundle}"', run_entrypoint(entrypoint, bundle),
                  preservation_check(bundle, output_name), vocabulary_check(bundle, output_name),
                  run_queries(out, query_files)]
    return 'set -e\n' + '\n'.join(steps)


def result_contract(graph, contracts):
    """contracts: {query_file: [expected column names]}, taken from the task instruction."""
    return py(r'''
import sys, json
g = load([sys.argv[1]])
bad = 0
for q, cols in json.loads(sys.argv[2]).items():
    got = [str(v) for v in g.query(Path(q).read_text()).vars]
    ok = got == cols
    bad += not ok
    print('CONTRACT', q, 'OK' if ok else 'MISMATCH', ','.join(got), sep='\t')
raise SystemExit(1 if bad else 0)
''', graph, json.dumps(contracts))


def sparql_probe(graph, query_text):
    """authored: the SPARQL text is model-written."""
    return py(r'''
import sys
g = load([sys.argv[1]])
for row in g.query(sys.argv[2]): print('\t'.join('' if v is None else str(v) for v in row))
''', graph, query_text)


